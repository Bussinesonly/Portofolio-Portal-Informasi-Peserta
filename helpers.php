/**
 * Mulai sesi dengan konfigurasi aman.
 */
function initSession(): void
{
    if (session_status() === PHP_SESSION_NONE) {
        session_start([
            'cookie_lifetime' => SESSION_LIFETIME,
            'cookie_httponly'  => true,
            'cookie_samesite'  => 'Lax',
            'use_strict_mode'  => true,
        ]);
    }
}

/**
 * Cek apakah peserta sudah terautentikasi.
 */
function isAuthenticated(): bool
{
    return isset($_SESSION['peserta_id'], $_SESSION['peserta_token']);
}

/**
 * Redirect ke URL tertentu.
 */
function redirect(string $url): never
{
    header('Location: ' . $url);
    exit;
}

/**
 * Escape output untuk HTML.
 */
function e(string $str): string
{
    return htmlspecialchars($str, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/**
 * Normalisasi nomor HP Indonesia.
 * Mengubah awalan +62, 62 menjadi 0.
 * Menghapus karakter non-digit kecuali awalan +.
 */
function normalizePhone(string $phone): string
{
    // Hapus spasi dan karakter umum
    $phone = preg_replace('/[\s\-\.\(\)]/', '', $phone);
    
    // Konversi +62 atau 62 di awal menjadi 0
    if (str_starts_with($phone, '+62')) {
        $phone = '0' . substr($phone, 3);
    } elseif (str_starts_with($phone, '62') && strlen($phone) > 10) {
        $phone = '0' . substr($phone, 2);
    }

    return $phone;
}

/**
 * Validasi format nomor HP.
 */
function isValidPhone(string $phone): bool
{
    // Harus dimulai dengan 0, diikuti 9–13 digit
    return (bool) preg_match('/^0\d{9,13}$/', $phone);
}

/**
 * Generate token unik untuk peserta.
 */
function generateToken(): string
{
    return bin2hex(random_bytes(32));
}

/**
 * Generate CSRF token.
 */
function csrfToken(): string
{
    if (empty($_SESSION['csrf_token'])) {
        $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf_token'];
}

/**
 * Validasi CSRF token.
 */
function validateCsrf(string $token): bool
{
    return isset($_SESSION['csrf_token']) && hash_equals($_SESSION['csrf_token'], $token);
}

