CREATE TABLE IF NOT EXISTS public.peserta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_lengkap VARCHAR(150) NOT NULL,
    departemen VARCHAR(100) NOT NULL,
    no_hp VARCHAR(20) NOT NULL,
    token VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_access TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_peserta_token ON public.peserta (token);
CREATE INDEX IF NOT EXISTS idx_peserta_no_hp ON public.peserta (no_hp);

CREATE TABLE IF NOT EXISTS public.informasi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    urutan INTEGER NOT NULL DEFAULT 0 CHECK (urutan >= 0),
    kategori VARCHAR(50) NOT NULL DEFAULT 'umum',
    judul VARCHAR(200) NOT NULL,
    ikon VARCHAR(50),
    konten TEXT NOT NULL,
    aktif BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_informasi_aktif_urutan
    ON public.informasi (aktif, urutan);

-- Aplikasi menggunakan koneksi Node.js di sisi server. Blokir akses langsung dari Data API.
ALTER TABLE public.peserta ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.informasi ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS informasi_set_updated_at ON public.informasi;
CREATE TRIGGER informasi_set_updated_at
BEFORE UPDATE ON public.informasi
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();
